// Command notices writes THIRD_PARTY_NOTICES: the license text of every Go
// module linked into the sapu binary. Run it with `make notices` after any
// change to go.mod. It is a build tool and is not part of the sapu binary.
//
// The module list comes from `go list -deps ./cmd/sapu` for the platform the
// release is built for (darwin, no cgo), so test-only modules are not listed.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const outputFile = "THIRD_PARTY_NOTICES"

const header = `Third-party Go modules in the sapu binary
=========================================

The sapu binary links the Go modules below. Each entry gives the module path,
its version and the full text of its license files, copied from the module.
Generated by "make notices" from go.mod; do not edit by hand.
Adapted data and fonts are listed in THIRD_PARTY_LICENSES.
`

type module struct {
	path    string
	version string
	dir     string
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	out, err := generate(root)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, outputFile), out, 0o644) //nolint:gosec // a file committed to the repository, readable like every other
}

// generate lists the modules linked into ./cmd/sapu under root and returns the
// text of THIRD_PARTY_NOTICES.
func generate(root string) ([]byte, error) {
	mods, err := listModules(root)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(header)
	for _, m := range mods {
		files, err := licenseFiles(m.dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.path, err)
		}
		fmt.Fprintf(&b, "\n\n%s\n%s@%s\n%s\n", rule, m.path, m.version, rule)
		for _, name := range files {
			text, err := os.ReadFile(filepath.Join(m.dir, name))
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&b, "\n--- %s ---\n\n%s\n", name, strings.TrimSpace(string(text)))
		}
	}
	return b.Bytes(), nil
}

var rule = strings.Repeat("=", 72)

// listModules returns the modules that provide packages of ./cmd/sapu, sorted
// by path, without the main module.
func listModules(root string) ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-f",
		"{{with .Module}}{{if not .Main}}{{.Path}}@{{.Version}} {{.Dir}}{{end}}{{end}}", "./cmd/sapu")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "GOOS=darwin", "GOARCH=arm64", "CGO_ENABLED=0")
	var stdout, stderr bytes.Buffer
	cmd.Stdout = &stdout
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return nil, fmt.Errorf("go list: %w\n%s", err, stderr.String())
	}
	seen := map[string]module{}
	for _, line := range strings.Split(stdout.String(), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		pathVersion, dir, ok := strings.Cut(line, " ")
		if !ok || dir == "" {
			return nil, fmt.Errorf("module %s is not in the module cache; run go mod download", pathVersion)
		}
		path, version, _ := strings.Cut(pathVersion, "@")
		seen[path] = module{path: path, version: version, dir: dir}
	}
	if len(seen) == 0 {
		return nil, errors.New("go list found no modules")
	}
	var mods []module
	for _, m := range seen {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].path < mods[j].path })
	return mods, nil
}

// licenseFiles returns the names of the LICENSE, LICENCE, COPYING and NOTICE
// files in the top folder of a module, sorted. A module without one is an
// error: we cannot ship it without its notice.
func licenseFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		upper := strings.ToUpper(e.Name())
		for _, prefix := range []string{"LICENSE", "LICENCE", "COPYING", "NOTICE"} {
			if strings.HasPrefix(upper, prefix) {
				names = append(names, e.Name())
				break
			}
		}
	}
	if len(names) == 0 {
		return nil, errors.New("no LICENSE, LICENCE, COPYING or NOTICE file")
	}
	sort.Strings(names)
	return names, nil
}
